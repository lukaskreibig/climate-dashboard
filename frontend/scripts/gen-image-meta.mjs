#!/usr/bin/env node
/**
 * Writes lib/imageMeta.ts from the files in public/images.
 *
 * next/image needs an intrinsic width and height for every photo it does not
 * import statically, and this story picks its photos by string at runtime. Left
 * to guesswork those numbers become a source of layout shift, so they are read
 * out of the file headers instead.
 *
 * Run after adding or replacing a photo:
 *   yarn node scripts/gen-image-meta.mjs
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const imagesDir = join(root, 'public', 'images');

/** PNG: the IHDR chunk is always first and always at a fixed offset. */
const readPng = (buf) =>
  buf.length > 24 && buf.readUInt32BE(0) === 0x89504e47
    ? { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) }
    : null;

/**
 * JPEG: walk the marker chain to the start-of-frame. SOF0 through SOF15 all
 * carry the size in the same place; the four markers that are not frames
 * (0xc4 Huffman, 0xc8, 0xcc) have to be skipped like any other segment.
 */
const readJpeg = (buf) => {
  if (buf.length < 4 || buf.readUInt16BE(0) !== 0xffd8) return null;
  let off = 2;
  while (off + 9 < buf.length) {
    if (buf[off] !== 0xff) {
      off += 1;
      continue;
    }
    const marker = buf[off + 1];
    if (marker === 0xd8 || marker === 0x01 || (marker >= 0xd0 && marker <= 0xd7)) {
      off += 2;
      continue;
    }
    const len = buf.readUInt16BE(off + 2);
    const isFrame =
      marker >= 0xc0 && marker <= 0xcf && marker !== 0xc4 && marker !== 0xc8 && marker !== 0xcc;
    if (isFrame) {
      return { height: buf.readUInt16BE(off + 5), width: buf.readUInt16BE(off + 7) };
    }
    off += 2 + len;
  }
  return null;
};

const entries = readdirSync(imagesDir)
  .filter((name) => /\.(jpe?g|png)$/i.test(name))
  .sort()
  .map((name) => {
    const buf = readFileSync(join(imagesDir, name));
    const size = /\.png$/i.test(name) ? readPng(buf) : readJpeg(buf);
    if (!size) throw new Error(`could not read the dimensions of ${name}`);
    return [`/images/${name}`, size];
  });

const body = entries
  .map(([src, { width, height }]) => `  "${src}": { width: ${width}, height: ${height} },`)
  .join('\n');

writeFileSync(
  join(root, 'lib', 'imageMeta.ts'),
  `/**
 * Generated by scripts/gen-image-meta.mjs. Do not edit by hand.
 *
 * Intrinsic pixel dimensions of everything in public/images, so next/image can
 * reserve the right box for a photo whose src is only known at runtime.
 */
export interface ImageSize {
  width: number;
  height: number;
}

export const IMAGE_META: Record<string, ImageSize> = {
${body}
};

/**
 * Falls back to a 3:2 landscape box. A missing entry means someone added a
 * photo without regenerating this file; the layout stays sane and the photo
 * still renders, it just loses its exact aspect ratio until the script is run.
 */
export const imageSize = (src: string): ImageSize =>
  IMAGE_META[src] ?? { width: 1500, height: 1000 };
`,
);

console.log(`wrote lib/imageMeta.ts with ${entries.length} images`);
